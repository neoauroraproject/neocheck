setup_directories() {
    log_info "Creating filesystem layout in $INSTALL_DIR..."
    mkdir -p "$INSTALL_DIR/config"
    mkdir -p "$INSTALL_DIR/database"
    mkdir -p "$INSTALL_DIR/logs"
    mkdir -p "$INSTALL_DIR/ssl"
    mkdir -p "$INSTALL_DIR/backups"
    mkdir -p "$INSTALL_DIR/src"
}

fetch_source() {
    log_info "Fetching NeoCheck source code..."
    if command -v git &> /dev/null; then
        if [ -d "$INSTALL_DIR/src/.git" ]; then
            log_info "Source already exists, pulling latest..."
            cd "$INSTALL_DIR/src" && git pull
        else
            git clone "$REPO_URL" "$INSTALL_DIR/src" || log_error "Failed to clone repository. Is the REPO_URL valid?"
        fi
    else
        log_info "Installing git..."
        apt-get update -y && apt-get install -y git
        git clone "$REPO_URL" "$INSTALL_DIR/src" || log_error "Failed to clone repository. Is the REPO_URL valid?"
    fi
}

generate_config() {
    log_info "Generating secure configurations..."
    
    log_info "Hashing password..."
    HASHED_PASS=$(docker run --rm alpine sh -c "apk add --no-cache apache2-utils >/dev/null 2>&1 && htpasswd -B -n -b user '$ADMIN_PASS'" | cut -d':' -f2)
    
    if [ -z "$HASHED_PASS" ]; then
        log_error "Failed to generate bcrypt hash."
    fi

    JWT_SECRET=$(openssl rand -hex 32)
    SESSION_SECRET=$(openssl rand -hex 32)

    # Determine Public URL
    if [ "$SSL_ENABLED" = "true" ]; then
        PUBLIC_URL="https://$PUBLIC_ADDRESS"
        log_info "Copying SSL certificates to internal storage..."
        cp "$SSL_CERT" "$INSTALL_DIR/ssl/server.crt"
        cp "$SSL_KEY" "$INSTALL_DIR/ssl/server.key"
        CONFIG_SSL_CERT="/opt/neocheck/ssl/server.crt"
        CONFIG_SSL_KEY="/opt/neocheck/ssl/server.key"
    else
        if [ "$SERVER_PORT" = "80" ]; then
            PUBLIC_URL="http://$PUBLIC_ADDRESS"
        else
            PUBLIC_URL="http://$PUBLIC_ADDRESS:$SERVER_PORT"
        fi
        CONFIG_SSL_CERT=""
        CONFIG_SSL_KEY=""
    fi

    cat <<EOF > "$INSTALL_DIR/config/config.yaml"
server:
  host: "0.0.0.0"
  port: 8080
branding:
  name: "$BRAND_NAME"
  subtitle: "Know your connection in seconds."
  logo: ""
  favicon: ""
  primary_color: "#8b5cf6"
  accent_color: "#6366f1"
  footer_text: "Managed by Immutable Diagnostics."
  copyright_text: "$BRAND_NAME"
  support_url: "https://github.com/neoauroraproject/neocheck/issues"
  github_url: "https://github.com/neoauroraproject/neocheck"
  documentation_url: "https://github.com/neoauroraproject/neocheck/tree/main/docs"
  public_url: "$PUBLIC_URL"
ssl:
  enabled: $SSL_ENABLED
  cert_path: "$CONFIG_SSL_CERT"
  key_path: "$CONFIG_SSL_KEY"
admin:
  username: "$ADMIN_USER"
  password_hash: "$HASHED_PASS"
security:
  session_secret: "$SESSION_SECRET"
  jwt_secret: "$JWT_SECRET"
providers:
  abuseipdb:
    enabled: false
    api_key: ""
  bigdatacloud:
    enabled: false
    api_key: ""
  ipqualityscore:
    enabled: false
    api_key: ""
  scamalytics:
    enabled: false
    api_key: ""
features:
  ipv6: true
  webrtc: true
  dns_leak: true
  service_check: true
  fraud_check: true
database:
  path: "/opt/neocheck/database/neocheck.db"
EOF
    log_success "config.yaml generated."
}

generate_docker_compose() {
    generate_docker_compose_for_port "$SERVER_PORT"
}

generate_docker_compose_for_port() {
    local port="$1"
    log_info "Generating docker-compose.yml..."
    cat <<EOF > "$INSTALL_DIR/docker-compose.yml"
services:
  backend:
    image: ghcr.io/neoauroraproject/neocheck-backend:latest
    ports:
      - "$port:8080"
    volumes:
      - ./config:/opt/neocheck/config
      - ./database:/opt/neocheck/database
      - ./ssl:/opt/neocheck/ssl
      - ./logs:/opt/neocheck/logs
      - ./backups:/opt/neocheck/backups
    restart: unless-stopped
    environment:
      - GIN_MODE=release
      - NEOCHECK_DATA_DIR=/opt/neocheck

  frontend:
    image: ghcr.io/neoauroraproject/neocheck-frontend:latest
    restart: unless-stopped
    depends_on:
      - backend
EOF
    log_success "docker-compose.yml generated."
}

detect_server_port() {
    local port=""
    if [ -f "$INSTALL_DIR/docker-compose.yml" ]; then
        port=$(grep -oE '[0-9]+:8080' "$INSTALL_DIR/docker-compose.yml" | head -1 | cut -d: -f1)
    fi
    echo "${port:-8080}"
}

config_ssl_enabled() {
    local cfg="$INSTALL_DIR/config/config.yaml"
    [ -f "$cfg" ] || return 1
    awk '/^ssl:/{block=1} block && /^[^[:space:]]/ && !/^ssl:/{block=0} block && /enabled:/{print; exit}' "$cfg" | grep -qE 'enabled:[[:space:]]*true'
}

probe_health() {
    local port="$1"
    if config_ssl_enabled; then
        curl -skf "https://127.0.0.1:$port/api/health" > /dev/null 2>&1
    else
        curl -sf "http://127.0.0.1:$port/api/health" > /dev/null 2>&1
    fi
}

containers_healthy_enough() {
    local ps_out
    if docker compose version &> /dev/null; then
        ps_out=$(docker compose ps 2>/dev/null)
    else
        ps_out=$(docker-compose ps 2>/dev/null)
    fi
    if echo "$ps_out" | grep -E 'backend|neocheck-backend' | grep -qE 'Restarting|Exited'; then
        return 1
    fi
    echo "$ps_out" | grep -E 'backend|neocheck-backend' | grep -q 'Up'
}

wait_for_health() {
    local port="$1"
    local ssl_note=""

    if config_ssl_enabled; then
        ssl_note=" (HTTPS)"
        log_info "SSL is enabled in config — using HTTPS for the health check."
    fi

    log_info "Waiting for application health check on port $port$ssl_note..."
    for i in {1..45}; do
        if probe_health "$port"; then
            log_success "Application is healthy and responding."
            return 0
        fi
        sleep 2
    done

    if containers_healthy_enough; then
        log_success "NeoCheck containers are running on port $port."
        if config_ssl_enabled; then
            log_info "Open the app with https:// (SSL is enabled in config.yaml)."
        fi
        return 0
    fi

    log_warn "Application did not become healthy in time."
    log_info "Container status:"
    if docker compose version &> /dev/null; then
        docker compose ps || true
        log_info "Recent logs:"
        docker compose logs --tail=40 || true
    else
        docker-compose ps || true
        docker-compose logs --tail=40 || true
    fi
    return 1
}

ensure_docker_compose() {
    local port
    port=$(detect_server_port)

    if [ ! -f "$INSTALL_DIR/docker-compose.yml" ]; then
        log_warn "docker-compose.yml missing. Regenerating..."
        generate_docker_compose_for_port "$port"
        return
    fi

    if ! grep -q "^[[:space:]]*frontend:" "$INSTALL_DIR/docker-compose.yml"; then
        log_warn "docker-compose.yml is outdated (missing frontend service). Regenerating..."
        generate_docker_compose_for_port "$port"
    fi
}

compose_up() {
    if docker compose version &> /dev/null; then
        docker compose up -d --force-recreate --remove-orphans --pull always
    else
        docker-compose up -d --force-recreate --remove-orphans --pull always
    fi
}

compose_pull() {
    if docker compose version &> /dev/null; then
        docker compose pull
    else
        docker-compose pull
    fi
}

compose_down() {
    if docker compose version &> /dev/null; then
        docker compose down --remove-orphans || true
    else
        docker-compose down --remove-orphans || true
    fi
}

disable_ssl_in_config() {
    local cfg="$1"
    awk '
        BEGIN { in_ssl=0 }
        /^ssl:/ { in_ssl=1 }
        in_ssl && /^[^[:space:]#]/ && !/^ssl:/ { in_ssl=0 }
        in_ssl && /^[[:space:]]*enabled:[[:space:]]*true/ {
            sub(/true[[:space:]]*$/, "false")
            in_ssl=0
        }
        { print }
    ' "$cfg" > "$cfg.new" && mv "$cfg.new" "$cfg"
}

fix_ssl_paths_in_config() {
    local cfg="$1"
    awk '
        BEGIN { in_ssl=0 }
        /^ssl:/ { in_ssl=1 }
        in_ssl && /^[^[:space:]#]/ && !/^ssl:/ { in_ssl=0 }
        in_ssl && /^[[:space:]]*cert_path:[[:space:]]*""/ {
            print "  cert_path: \"/opt/neocheck/ssl/server.crt\""
            next
        }
        in_ssl && /^[[:space:]]*key_path:[[:space:]]*""/ {
            print "  key_path: \"/opt/neocheck/ssl/server.key\""
            next
        }
        { print }
    ' "$cfg" > "$cfg.new" && mv "$cfg.new" "$cfg"
}

backup_installation_data() {
    local stamp backup_dir
    stamp=$(date +%Y%m%d-%H%M%S)
    backup_dir="$INSTALL_DIR/backups/pre-update-$stamp"
    mkdir -p "$backup_dir"

    if [ -f "$INSTALL_DIR/config/config.yaml" ]; then
        cp -a "$INSTALL_DIR/config/config.yaml" "$backup_dir/config.yaml"
    fi
    if [ -f "$INSTALL_DIR/database/neocheck.db" ]; then
        cp -a "$INSTALL_DIR/database/neocheck.db" "$backup_dir/neocheck.db"
    fi

    log_info "Backed up config and database to $backup_dir"
}

installation_exists() {
    [ -f "$INSTALL_DIR/config/config.yaml" ]
}
repair_ssl_config() {
    local cfg="$INSTALL_DIR/config/config.yaml"
    local cert="$INSTALL_DIR/ssl/server.crt"
    local key="$INSTALL_DIR/ssl/server.key"
    [ -f "$cfg" ] || return 0

    if ! awk '/^ssl:/{block=1} block && /^[^[:space:]]/ && !/^ssl:/{block=0} block && /enabled:/{print; exit}' "$cfg" | grep -qE 'enabled:[[:space:]]*true'; then
        return 0
    fi

    if [ ! -f "$cert" ] || [ ! -f "$key" ]; then
        log_warn "SSL is enabled but certificate files are missing. Disabling SSL only (providers and admin settings are preserved)."
        disable_ssl_in_config "$cfg"
        return 0
    fi

    if grep -qE 'cert_path:[[:space:]]*""' "$cfg" || grep -qE 'cert_path:[[:space:]]*$' "$cfg"; then
        log_warn "Repairing empty SSL certificate paths in config.yaml..."
        fix_ssl_paths_in_config "$cfg"
    fi
}

start_application() {
    log_info "Starting NeoCheck application via Docker Compose..."
    cd "$INSTALL_DIR"

    compose_pull || log_warn "Some images could not be pulled. Continuing with available images."
    compose_up

    wait_for_health "$SERVER_PORT" || log_warn "Application is taking longer than expected to start. Please check logs."
}

finish_installation() {
    echo -e "\n============================================="
    echo -e "${GREEN}✨ NeoCheck successfully installed! ✨${NC}"
    echo -e "=============================================\n"
    
    PROTOCOL="http"
    if [ "$SSL_ENABLED" = true ]; then
        PROTOCOL="https"
    fi

    echo -e "🌐 ${CYAN}Application URL:${NC}  $PROTOCOL://$PUBLIC_ADDRESS:$SERVER_PORT"
    echo -e "🛡️  ${CYAN}Admin URL:${NC}        $PROTOCOL://$PUBLIC_ADDRESS:$SERVER_PORT/admin"
    echo -e "👤 ${CYAN}Admin Username:${NC}   $ADMIN_USER"
    echo -e ""
    echo -e "📁 ${CYAN}Installation Directory:${NC}  $INSTALL_DIR"
    echo -e "📄 ${CYAN}Configuration File:${NC}      $INSTALL_DIR/config/config.yaml"
    echo -e "📜 ${CYAN}Log Directory:${NC}           $INSTALL_DIR/logs"
    echo -e "🗄️  ${CYAN}Database Location:${NC}       $INSTALL_DIR/database/neocheck.db"
    echo -e "\n============================================="
    echo -e "To view logs: cd $INSTALL_DIR && docker compose logs -f"
}

action_install() {
    echo -e "${CYAN}Welcome to NeoCheck Installer${NC}\n"
    check_root
    check_os
    check_dependencies

    if installation_exists; then
        log_error "NeoCheck is already installed at $INSTALL_DIR. Use option 2 (update) to upgrade without losing admin credentials, API keys, or database."
    fi
    
    prompt_port
    prompt_address
    prompt_admin
    prompt_ssl
    prompt_branding
    
    setup_directories
    fetch_source
    generate_config
    generate_docker_compose
    
    start_application
    finish_installation
}

action_update() {
    check_root
    log_info "Checking current installation..."
    if [ ! -d "$INSTALL_DIR" ] || [ ! -f "$INSTALL_DIR/docker-compose.yml" ]; then
        log_error "NeoCheck installation not found in $INSTALL_DIR. Please run installation first."
    fi

    log_info "Starting update process..."

    # 1. Update source code if present (reference only; runtime uses Docker images)
    if [ -d "$INSTALL_DIR/src/.git" ]; then
        log_info "Updating source code repository..."
        cd "$INSTALL_DIR/src"
        git pull || log_warn "Failed to pull latest git changes. Proceeding anyway."
    fi

    cd "$INSTALL_DIR"
    SERVER_PORT=$(detect_server_port)
    backup_installation_data
    ensure_docker_compose
    repair_ssl_config

    # Pull latest images and recreate containers (keep bind-mounted config/database)
    log_info "Pulling latest Docker images..."
    compose_pull || log_warn "Some images could not be pulled. Continuing with available images."

    log_info "Starting containers with latest images..."
    compose_up

    # 4. Verify the app actually came back
    if wait_for_health "$SERVER_PORT"; then
        log_info "Pruning unused Docker images..."
        docker image prune -f || true
        log_success "NeoCheck has been successfully updated to the latest version!"
    else
        log_warn "Update completed but the health check did not respond in time."
        log_info "Check status: cd $INSTALL_DIR && docker compose ps && docker compose logs --tail=40 backend"
    fi
}

action_uninstall() {
    log_info "Starting uninstallation process..."
    
    if [ -d "$INSTALL_DIR" ]; then
        cd "$INSTALL_DIR"
        
        log_info "Stopping containers and freeing up ports..."
        if docker compose version &> /dev/null; then
            docker compose down -v || true
        else
            docker-compose down -v || true
        fi
        
        cd /
        log_info "Removing installation directory: $INSTALL_DIR"
        rm -rf "$INSTALL_DIR"
        
        log_success "NeoCheck has been completely uninstalled and all ports are freed!"
    else
        log_warn "Installation directory $INSTALL_DIR not found. Nothing to uninstall."
    fi
}

action_repair() {
    log_info "Repair functionality is handled by reinstalling via Option 1."
}

# Main Command Router
show_menu() {
    neo_banner "Setup & Manager"
    neo_ad cli
    neo_menu "What would you like to do?" \
        "Install NeoCheck|set up the dashboard with Docker" \
        "Update NeoCheck|pull the latest images; settings and data stay" \
        "Uninstall NeoCheck|stop the containers and remove the install folder"
    case "$NEO_CHOICE" in
        1) action_install ;;
        2) action_update ;;
        3) action_uninstall ;;
        *) log_info "Exiting."; exit 0 ;;
    esac
}

if [ -z "$1" ]; then
    show_menu
else
    COMMAND=$1
    case "$COMMAND" in
        install) action_install ;;
        update) action_update ;;
        uninstall) action_uninstall ;;
        repair) log_error "Repair was removed to prevent accidental data loss. Use option 2 (update) instead." ;;
        *) log_error "Unknown command: $COMMAND. Valid commands: install, update, uninstall, repair." ;;
    esac
fi
